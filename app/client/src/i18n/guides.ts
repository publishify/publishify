/** Guides shared by numbered chapters ("İkinci deneme", "Sahne 4", "Sayfa 7"). */
export function guideFor(tr: string): [string, string] | undefined {
  if (guides[tr]) return guides[tr];
  if (/deneme$/.test(tr)) return guides["Birinci deneme"];
  if (/^Sahne \d+$/.test(tr)) return guides["Sahne"];
  if (/^Sayfa \d+$/.test(tr)) return guides["Sayfa"];
  if (/bölüm$/.test(tr)) return guides["Birinci bölüm"];
  return undefined;
}

