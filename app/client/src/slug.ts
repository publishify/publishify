/** Address (slug) suggestion: Turkish characters are simplified; returns empty for a title with no Latin letters. */
export const slugify = (s: string): string =>
  s
    .replace(/\u0130/g, "i")
    .toLowerCase()
    .replace(/\u00e7/g, "c")
    .replace(/\u011f/g, "g")
    .replace(/\u0131/g, "i")
    .replace(/\u00f6/g, "o")
    .replace(/\u015f/g, "s")
    .replace(/\u00fc/g, "u")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60)
    .replace(/-+$/g, "");
